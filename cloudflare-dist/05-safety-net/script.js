const languageSelect = document.querySelector("#language-select");
const menuToggle = document.querySelector(".menu-toggle");
const primaryNav = document.querySelector("#primary-nav");
const menuLabel = document.querySelector(".menu-label");
let currentLanguage = "en";

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  currentLanguage = translations[language] ? language : "en";
  document.documentElement.lang = currentLanguage;
  document.title = pageTitles[currentLanguage];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = dictionary[key] ?? translations.en[key];
    if (!value) return;
    const attribute = element.dataset.i18nAttr;
    if (attribute) element.setAttribute(attribute, value);
    else element.textContent = value;
  });

  languageSelect.value = currentLanguage;
  try {
    window.localStorage.setItem("civic-guardian-lang", currentLanguage);
  } catch {}
}

function setMenu(open) {
  menuToggle.setAttribute("aria-expanded", String(open));
  primaryNav.classList.toggle("is-open", open);
  menuLabel.dataset.i18n = open ? "menuClose" : "menuOpen";
  applyLanguage(currentLanguage);
}

languageSelect.addEventListener("change", (event) => applyLanguage(event.target.value));
menuToggle.addEventListener("click", () => setMenu(menuToggle.getAttribute("aria-expanded") !== "true"));
primaryNav.addEventListener("click", () => {
  if (window.matchMedia("(max-width: 767px)").matches) setMenu(false);
});
document.addEventListener("click", (event) => {
  if (!primaryNav.contains(event.target) && !menuToggle.contains(event.target)) setMenu(false);
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
    setMenu(false);
    menuToggle.focus();
  }
});

try {
  const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
  const savedLanguage = window.localStorage.getItem("civic-guardian-lang");
  const initialLanguage = requestedLanguage && translations[requestedLanguage] ? requestedLanguage : savedLanguage;
  applyLanguage(initialLanguage && translations[initialLanguage] ? initialLanguage : "en");
} catch {
  applyLanguage("en");
}

const select = document.querySelector("#language-select");
const nav = document.querySelector("#primary-nav");
const menuToggle = document.querySelector(".menu-toggle");
const status = document.querySelector("#language-status");
const description = document.querySelector('meta[name="description"]');
const supported = Object.keys(translations);
const queryLanguage = new URLSearchParams(window.location.search).get("lang");
const storedLanguage = (() => {
  try {
    return window.localStorage.getItem("civic-guardian-lang");
  } catch {
    return null;
  }
})();
const browserLanguage = navigator.language.toLowerCase() === "zh-tw" ? "zh-TW" : navigator.language.split("-")[0];
let activeLanguage = supported.includes(queryLanguage)
  ? queryLanguage
  : supported.includes(storedLanguage)
    ? storedLanguage
    : supported.includes(browserLanguage)
      ? browserLanguage
      : "en";

function setMenu(open, restoreFocus = false) {
  const copy = translations[activeLanguage] || translations.en;
  nav.dataset.open = String(open);
  menuToggle.setAttribute("aria-expanded", String(open));
  menuToggle.setAttribute("aria-label", open ? copy.menuCloseLabel : copy.menuOpenLabel);
  if (restoreFocus) {
    menuToggle.focus();
  }
}

function render(language, announce = false) {
  const copy = translations[language] || translations.en;
  activeLanguage = language;
  document.documentElement.lang = language;
  document.title = copy.title;
  description.content = copy.metaDescription;
  select.value = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":");
      if (attribute && copy[key] !== undefined) {
        element.setAttribute(attribute, copy[key]);
      }
    });
  });

  document.querySelectorAll("[data-page-link]").forEach((link) => {
    const baseHref = link.dataset.baseHref || link.getAttribute("href");
    link.dataset.baseHref = baseHref;
    const url = new URL(baseHref, window.location.href);
    url.searchParams.set("lang", language);
    link.href = url.href;
  });

  setMenu(false);

  try {
    window.localStorage.setItem("civic-guardian-lang", language);
  } catch {
  }

  if (announce) {
    status.textContent = copy.languageChanged;
    const currentUrl = new URL(window.location.href);
    currentUrl.searchParams.set("lang", language);
    window.history.replaceState({}, "", currentUrl);
  }
}

select.addEventListener("change", () => {
  render(select.value, true);
});

menuToggle.addEventListener("click", () => {
  setMenu(menuToggle.getAttribute("aria-expanded") !== "true");
});

nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => setMenu(false));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
    setMenu(false, true);
  }
});

window.matchMedia("(min-width: 68.76rem)").addEventListener("change", (event) => {
  if (event.matches) {
    setMenu(false);
  }
});

render(activeLanguage);

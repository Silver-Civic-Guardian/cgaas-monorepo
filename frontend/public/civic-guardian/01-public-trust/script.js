const languageSelect = document.querySelector("#language-select");
const languageStatus = document.querySelector("#language-status");
const footerLanguageValue = document.querySelector("#footer-language-value");
const menuToggle = document.querySelector(".menu-toggle");
const supportedLocales = Object.keys(translations);

document.documentElement.classList.add("js-enabled");

function readSavedLocale() {
  try {
    const saved = window.localStorage.getItem("civic-guardian-lang");
    return supportedLocales.includes(saved) ? saved : "en";
  } catch {
    return "en";
  }
}

function writeSavedLocale(locale) {
  try {
    window.localStorage.setItem("civic-guardian-lang", locale);
  } catch {
  }
}

function setAttributeTranslations(copy) {
  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":");
      if (attribute && key && copy[key]) {
        element.setAttribute(attribute, copy[key]);
      }
    });
  });
}

function applyLocale(locale, announce = false) {
  const activeLocale = supportedLocales.includes(locale) ? locale : "en";
  const copy = translations[activeLocale];
  document.documentElement.lang = activeLocale;
  document.documentElement.dataset.locale = activeLocale;
  document.title = copy.title;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (typeof value === "string") {
      element.textContent = value;
    }
  });

  setAttributeTranslations(copy);
  if (languageSelect) {
    languageSelect.value = activeLocale;
  }
  if (footerLanguageValue) {
    footerLanguageValue.textContent = copy.languageName;
  }
  if (announce && languageStatus) {
    languageStatus.textContent = copy.languageChanged;
  }
}

function setMenuState(open) {
  if (!menuToggle) return;
  document.body.classList.toggle("nav-open", open);
  menuToggle.setAttribute("aria-expanded", String(open));
  const copy = translations[document.documentElement.dataset.locale || "en"];
  menuToggle.setAttribute("aria-label", open ? copy.menuCloseLabel : copy.menuLabel);
}

languageSelect?.addEventListener("change", (event) => {
  const locale = event.target.value;
  writeSavedLocale(locale);
  applyLocale(locale, true);
  setMenuState(false);
});

menuToggle?.addEventListener("click", () => {
  setMenuState(!document.body.classList.contains("nav-open"));
});

document.querySelectorAll(".primary-nav a").forEach((link) => {
  link.addEventListener("click", () => setMenuState(false));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && menuToggle?.getAttribute("aria-expanded") === "true") {
    setMenuState(false);
    menuToggle.focus();
  }
});

if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  document.querySelectorAll("[data-reveal]").forEach((element) => revealObserver.observe(element));
} else {
  document.querySelectorAll("[data-reveal]").forEach((element) => element.classList.add("is-visible"));
}

